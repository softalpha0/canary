/**
 * Demo accounts: deployer, lp1, buyer1, reporter (eth_secp256k1, coin type 60).
 *
 *   pnpm accounts create            generate 4 mnemonics into .env (refuses to overwrite)
 *   pnpm accounts list              addresses, balances, PQC key and window status
 *   pnpm accounts register <name|all>  register ML-DSA-87 key with proof of possession (S1)
 *   pnpm accounts fund <name> <qor> send QOR from deployer (hybrid-signed bank send)
 *
 * Secrets go to .env only and are never printed. Public addresses are written
 * to deployments/accounts.json (needed for the project page).
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { generateMnemonic, msg } from "@qorechain/sdk";
import { ACCOUNT_NAMES, config, mnemonicVar, type AccountName } from "./config.js";
import { ENV_PATH, REPO_ROOT, loadEnv } from "./lib/env.js";
import {
  balanceUqor,
  fmtQor,
  loadAccount,
  pqcStatus,
  publicInfo,
  registerPqcKey,
  sendNative,
  windowStatus,
} from "./lib/qore.js";

const ACCOUNTS_JSON = resolve(REPO_ROOT, "deployments", "accounts.json");

function isName(s: string | undefined): s is AccountName {
  return ACCOUNT_NAMES.includes(s as AccountName);
}

async function writePublicJson() {
  const out = [];
  for (const n of ACCOUNT_NAMES) out.push(publicInfo(n, await loadAccount(n)));
  mkdirSync(resolve(REPO_ROOT, "deployments"), { recursive: true });
  writeFileSync(ACCOUNTS_JSON, JSON.stringify(out, null, 2) + "\n");
  return out;
}

async function create() {
  loadEnv();
  const existing = existsSync(ENV_PATH) ? readFileSync(ENV_PATH, "utf8") : "";
  const present = ACCOUNT_NAMES.filter((n) => new RegExp(`^${mnemonicVar(n)}=.+`, "m").test(existing));
  if (present.length > 0) {
    throw new Error(`Refusing to overwrite existing mnemonics in .env: ${present.map(mnemonicVar).join(", ")}`);
  }
  // Strip empty placeholder lines (copied from .env.example) so the new values are the only definitions.
  const cleaned = existing
    .split("\n")
    .filter((l) => !ACCOUNT_NAMES.some((n) => l.trim() === `${mnemonicVar(n)}=`))
    .join("\n");
  const lines = ACCOUNT_NAMES.map((n) => `${mnemonicVar(n)}="${generateMnemonic()}"`);
  writeFileSync(ENV_PATH, cleaned.replace(/\n*$/, "\n") + "\n# Demo accounts (testnet only) — generated by pnpm accounts create\n" + lines.join("\n") + "\n", {
    mode: 0o600,
  });
  for (const l of lines) process.env[l.slice(0, l.indexOf("="))] = l.slice(l.indexOf("=") + 2, -1);
  const pub = await writePublicJson();
  console.table(pub);
  console.log(`Mnemonics written to .env (git-ignored). Public addresses → deployments/accounts.json`);
}

async function list() {
  const rows = [];
  for (const n of ACCOUNT_NAMES) {
    const a = await loadAccount(n);
    const [bal, pqc, win] = await Promise.all([
      balanceUqor(a.cosmos),
      pqcStatus(a.cosmos).catch((e: Error) => ({ registered: false, error: e.message })),
      windowStatus(a.cosmos).catch(() => undefined),
    ]);
    rows.push({
      name: n,
      qor: a.cosmos,
      evm: a.evm,
      balance: fmtQor(bal),
      pqcKey: pqc.registered ? `yes${"possessionProven" in pqc && pqc.possessionProven ? " (proven)" : " (NOT proven)"}` : "no",
      window: win?.found
        ? `${win.live ? "live" : "dead"} txs=${win.remainingTxs} blocks=${win.remainingBlocks} targets=${win.allowedTargets.length || "any"}`
        : "none",
    });
  }
  console.table(rows);
}

async function register(which: string | undefined) {
  const names = which === "all" ? [...ACCOUNT_NAMES] : isName(which) ? [which] : [];
  if (names.length === 0) throw new Error("Usage: pnpm accounts register <deployer|lp1|buyer1|reporter|all>");
  for (const n of names) {
    const a = await loadAccount(n);
    const r = await registerPqcKey(a);
    if (r.alreadyRegistered) console.log(`${n} ${a.cosmos}: already registered (proven=${r.status.possessionProven})`);
    else console.log(`${n} ${a.cosmos}: registered, tx ${r.txHash} at height ${r.height}`);
  }
}

async function fund(to: string | undefined, qor: string | undefined) {
  if (!isName(to) || to === "deployer" || !qor) throw new Error("Usage: pnpm accounts fund <lp1|buyer1|reporter> <QOR>");
  const from = await loadAccount("deployer");
  const dest = await loadAccount(to);
  const uqor = BigInt(Math.round(Number(qor) * 1e6));
  const send = msg.bank.send({ fromAddress: from.cosmos, toAddress: dest.cosmos, amount: [{ denom: config.denom, amount: uqor.toString() }] });
  const res = await sendNative(from, [send], { gas: 300_000n });
  console.log(`deployer → ${to} ${fmtQor(uqor)}: tx ${res.transactionHash} height ${res.height}`);
}

const [cmd, a1, a2] = process.argv.slice(2);
const run = { create, list, register: () => register(a1), fund: () => fund(a1, a2), pub: writePublicJson }[cmd ?? ""];
if (!run) {
  console.error("Usage: pnpm accounts <create|list|register|fund|pub>");
  process.exit(1);
}
run().catch((e: Error) => {
  console.error(`Error: ${e.message}`);
  process.exit(1);
});
